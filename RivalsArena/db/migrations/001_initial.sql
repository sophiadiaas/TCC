
-- =========================================
-- 1. USUARIOS
-- =========================================

CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT NOT NULL UNIQUE,
    email TEXT NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    name TEXT NOT NULL,
    bio TEXT NOT NULL DEFAULT '',
    region TEXT NOT NULL DEFAULT 'Brasil',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- =========================================
-- 2. SESSOES
-- =========================================

CREATE TABLE IF NOT EXISTS sessions (
    token_hash TEXT PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    expires_at BIGINT NOT NULL
);

-- =========================================
-- 3. JOGOS
-- =========================================

CREATE TABLE IF NOT EXISTS games (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE,
    genre TEXT NOT NULL,
    description TEXT NOT NULL,
    platforms TEXT NOT NULL,
    owner_id BIGINT REFERENCES users(id)
);

-- =========================================
-- 4. EQUIPES
-- =========================================

CREATE TABLE IF NOT EXISTS teams (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE,
    game_id BIGINT NOT NULL REFERENCES games(id),
    captain_id BIGINT NOT NULL REFERENCES users(id),
    description TEXT NOT NULL DEFAULT ''
);

-- =========================================
-- 5. MEMBROS DAS EQUIPES
-- =========================================

CREATE TABLE IF NOT EXISTS team_members (
    team_id BIGINT NOT NULL REFERENCES teams(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    PRIMARY KEY (team_id, user_id)
);

-- =========================================
-- 6. CAMPEONATOS
-- =========================================

CREATE TABLE IF NOT EXISTS tournaments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    game_id BIGINT NOT NULL REFERENCES games(id),
    owner_id BIGINT NOT NULL REFERENCES users(id),
    capacity INTEGER NOT NULL CHECK (capacity BETWEEN 2 AND 64),
    team_size INTEGER NOT NULL CHECK (team_size BETWEEN 1 AND 8),
    starts_at TIMESTAMPTZ NOT NULL,
    status TEXT NOT NULL DEFAULT 'open'
        CHECK (status IN ('open', 'running', 'finished')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- =========================================
-- 7. INSCRICOES
-- =========================================

CREATE TABLE IF NOT EXISTS registrations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tournament_id BIGINT NOT NULL REFERENCES tournaments(id) ON DELETE CASCADE,
    team_id BIGINT NOT NULL REFERENCES teams(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (tournament_id, team_id)
);

-- =========================================
-- 8. JOGADORES INSCRITOS
-- =========================================

CREATE TABLE IF NOT EXISTS registration_players (
    registration_id BIGINT NOT NULL REFERENCES registrations(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES users(id),
    PRIMARY KEY (registration_id, user_id)
);

-- =========================================
-- 9. PARTIDAS
-- =========================================

CREATE TABLE IF NOT EXISTS matches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tournament_id BIGINT NOT NULL REFERENCES tournaments(id) ON DELETE CASCADE,
    round INTEGER NOT NULL,
    position INTEGER NOT NULL,
    team_a BIGINT REFERENCES teams(id),
    team_b BIGINT REFERENCES teams(id),
    score_a INTEGER,
    score_b INTEGER,
    winner_id BIGINT REFERENCES teams(id),
    status TEXT NOT NULL DEFAULT 'waiting'
        CHECK (status IN ('waiting', 'ready', 'done', 'bye')),
    scheduled_at TIMESTAMPTZ,
    stream_url TEXT NOT NULL DEFAULT '',
    completed_at TIMESTAMPTZ,
    UNIQUE (tournament_id, round, position)
);

-- =========================================
-- 10. PUBLICACOES
-- =========================================

CREATE TABLE IF NOT EXISTS posts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    text TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- =========================================
-- 11. CURTIDAS
-- =========================================

CREATE TABLE IF NOT EXISTS likes (
    post_id BIGINT NOT NULL REFERENCES posts(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    PRIMARY KEY (post_id, user_id)
);

-- =========================================
-- 12. COMENTARIOS
-- =========================================

CREATE TABLE IF NOT EXISTS comments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id BIGINT NOT NULL REFERENCES posts(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    text TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- =========================================
-- 13. INDICES
-- =========================================

CREATE UNIQUE INDEX IF NOT EXISTS users_username_lower_unique ON users (LOWER(username));
CREATE UNIQUE INDEX IF NOT EXISTS users_email_lower_unique ON users (LOWER(email));

CREATE INDEX IF NOT EXISTS idx_matches_tournament
ON matches(tournament_id, round, position);

CREATE INDEX IF NOT EXISTS idx_reg_players_user
ON registration_players(user_id);

CREATE INDEX IF NOT EXISTS idx_posts_created
ON posts(created_at);

CREATE INDEX IF NOT EXISTS idx_comments_post
ON comments(post_id);

CREATE INDEX IF NOT EXISTS idx_registrations_team
ON registrations(team_id);

CREATE INDEX IF NOT EXISTS idx_members_user
ON team_members(user_id);
