CREATE TABLE IF NOT EXISTS public.users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT NOT NULL UNIQUE,
    email TEXT NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    name TEXT NOT NULL,
    bio TEXT NOT NULL DEFAULT '',
    region TEXT NOT NULL DEFAULT 'Brasil',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.sessions (
    token_hash TEXT PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    expires_at BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS public.games (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE,
    genre TEXT NOT NULL,
    description TEXT NOT NULL,
    platforms TEXT NOT NULL,
    owner_id BIGINT REFERENCES public.users(id)
);

CREATE TABLE IF NOT EXISTS public.teams (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE,
    game_id BIGINT NOT NULL REFERENCES public.games(id),
    captain_id BIGINT NOT NULL REFERENCES public.users(id),
    description TEXT NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS public.team_members (
    team_id BIGINT NOT NULL REFERENCES public.teams(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    PRIMARY KEY (team_id, user_id)
);

CREATE TABLE IF NOT EXISTS public.tournaments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    game_id BIGINT NOT NULL REFERENCES public.games(id),
    owner_id BIGINT NOT NULL REFERENCES public.users(id),
    capacity INTEGER NOT NULL CHECK (capacity BETWEEN 2 AND 64),
    team_size INTEGER NOT NULL CHECK (team_size BETWEEN 1 AND 8),
    starts_at TIMESTAMPTZ NOT NULL,
    status TEXT NOT NULL DEFAULT 'open'
        CHECK (status IN ('open', 'running', 'finished')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.registrations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tournament_id BIGINT NOT NULL REFERENCES public.tournaments(id) ON DELETE CASCADE,
    team_id BIGINT NOT NULL REFERENCES public.teams(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (tournament_id, team_id)
);

CREATE TABLE IF NOT EXISTS public.registration_players (
    registration_id BIGINT NOT NULL REFERENCES public.registrations(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES public.users(id),
    PRIMARY KEY (registration_id, user_id)
);

CREATE TABLE IF NOT EXISTS public.matches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tournament_id BIGINT NOT NULL REFERENCES public.tournaments(id) ON DELETE CASCADE,
    round INTEGER NOT NULL,
    position INTEGER NOT NULL,
    team_a BIGINT REFERENCES public.teams(id),
    team_b BIGINT REFERENCES public.teams(id),
    score_a INTEGER,
    score_b INTEGER,
    winner_id BIGINT REFERENCES public.teams(id),
    status TEXT NOT NULL DEFAULT 'waiting'
        CHECK (status IN ('waiting', 'ready', 'done', 'bye')),
    scheduled_at TIMESTAMPTZ,
    stream_url TEXT NOT NULL DEFAULT '',
    completed_at TIMESTAMPTZ,
    UNIQUE (tournament_id, round, position)
);

CREATE TABLE IF NOT EXISTS public.posts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    text TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.likes (
    post_id BIGINT NOT NULL REFERENCES public.posts(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    PRIMARY KEY (post_id, user_id)
);

CREATE TABLE IF NOT EXISTS public.comments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id BIGINT NOT NULL REFERENCES public.posts(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    text TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE UNIQUE INDEX IF NOT EXISTS users_username_lower_unique
    ON public.users (LOWER(username));
CREATE UNIQUE INDEX IF NOT EXISTS users_email_lower_unique
    ON public.users (LOWER(email));
CREATE INDEX IF NOT EXISTS idx_matches_tournament
    ON public.matches(tournament_id, round, position);
CREATE INDEX IF NOT EXISTS idx_reg_players_user
    ON public.registration_players(user_id);
CREATE INDEX IF NOT EXISTS idx_posts_created
    ON public.posts(created_at);
CREATE INDEX IF NOT EXISTS idx_comments_post
    ON public.comments(post_id);
CREATE INDEX IF NOT EXISTS idx_registrations_team
    ON public.registrations(team_id);
CREATE INDEX IF NOT EXISTS idx_members_user
    ON public.team_members(user_id);

CREATE TABLE IF NOT EXISTS public.schema_migrations (
    name TEXT PRIMARY KEY,
    applied_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

